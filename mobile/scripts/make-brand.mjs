// Renders every icon / splash from frontend/brand/*.svg and writes frontend/js/brand.js (inline logo for the app UI).
//   cd mobile && node scripts/make-brand.mjs
import sharp from "sharp";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const fe = join(root, "frontend"), brand = join(fe, "brand"), icons = join(fe, "icons"), assets = join(root, "mobile", "assets");
mkdirSync(icons, { recursive: true });
const markSvg = readFileSync(join(brand, "fieldwise-mark.svg"), "utf8");
const logoSvg = readFileSync(join(brand, "fieldwise-logo.svg"), "utf8");
const inner = s => s.replace(/<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "");   // children only
const markBody = inner(markSvg);
const TILE = ["#f0fdfa", "#ccfbf1"];

// a square tile with the mark centred at `scale` of the tile
const tile = (size, scale, { bg = true, flat } = {}) => {
  const k = (size * scale) / 512, o = (size - 512 * k) / 2;
  const fill = flat || "url(#tile)";
  return Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}">
    <defs><linearGradient id="tile" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="${TILE[0]}"/><stop offset="1" stop-color="${TILE[1]}"/></linearGradient></defs>
    ${bg ? `<rect width="${size}" height="${size}" fill="${fill}"/>` : ""}<g transform="translate(${o} ${o}) scale(${k})">${markBody}</g></svg>`);
};
const png = (buf, file, size) => sharp(buf).resize(size, size).png().toFile(file);

// web / PWA icons
await png(tile(1024, 0.80), join(icons, "icon-192.png"), 192);
await png(tile(1024, 0.80), join(icons, "icon-512.png"), 512);
await png(tile(1024, 0.58), join(icons, "icon-maskable-512.png"), 512);        // full bleed, mark inside the safe zone
await png(tile(1024, 0.80), join(icons, "apple-touch-icon.png"), 180);
await png(tile(1024, 0.98, { bg: false }), join(icons, "favicon-32.png"), 32);

// square SVG icon (favicon + fallback)
writeFileSync(join(fe, "icon.svg"), `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512"><defs><linearGradient id="tile" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="${TILE[0]}"/><stop offset="1" stop-color="${TILE[1]}"/></linearGradient></defs><rect width="512" height="512" rx="112" fill="url(#tile)"/><g transform="translate(51 51) scale(0.8)">${markBody}</g></svg>\n`);

// native app assets (@capacitor/assets)
await png(tile(1024, 0.80), join(assets, "icon-only.png"), 1024);
await png(tile(1024, 0.52, { bg: false }), join(assets, "icon-foreground.png"), 1024);   // Android adaptive foreground
await sharp({ create: { width: 1024, height: 1024, channels: 3, background: "#e6faf6" } }).png().toFile(join(assets, "icon-background.png"));

// splash screens: the full logo on a plain background
const lockup = (s, w) => sharp(Buffer.from(s), { density: 300 }).resize({ width: w }).png().toBuffer();
const dark = logoSvg.replace("#0b3b38", "#e8ecf1").replace(/fill="#0f766e">wise/, 'fill="#2dd4bf">wise').replace("#5b6b6a", "#93a0b1");
for (const [name, bg, svg] of [["splash.png", "#f6f7f9", logoSvg], ["splash-dark.png", "#0c1117", dark]]) {
  const l = await lockup(svg, 1500);
  await sharp({ create: { width: 2732, height: 2732, channels: 3, background: bg } }).composite([{ input: l, gravity: "center" }]).png().toFile(join(assets, name));
}

// inline logos for the app (colours follow light/dark theme through CSS variables)
const themed = s => s.replace('fill="#0b3b38"', 'class="w1" fill="#0b3b38"').replace('<tspan fill="#0f766e">', '<tspan class="w2" fill="#0f766e">').replace('fill="#5b6b6a"', 'class="w3" fill="#5b6b6a"');
const full = themed(logoSvg).replace(/<svg ([^>]*)>/, '<svg class="logo" $1 focusable="false">');
const compact = full.replace(/<text[^>]*class="w3"[^>]*>.*?<\/text>/s, "").replace('viewBox="0 0 1260 512"', 'viewBox="30 20 1230 470"');
writeFileSync(join(fe, "js", "brand.js"), `// Generated by mobile/scripts/make-brand.mjs from frontend/brand/*.svg - do not edit by hand.\nexport const LOGO_FULL = ${JSON.stringify(full)};\nexport const LOGO_COMPACT = ${JSON.stringify(compact)};\n`);
console.log("brand assets written");
